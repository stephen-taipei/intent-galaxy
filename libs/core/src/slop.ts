export const SLOP_BLOCK: RegExp[] = [
  /提升|加強|完善|打造|賦能|全面(?!屏)|推動|深化|落實|兼顧/u,
  /優化(?!器)/u, /(?<!持續)整合(?!測試)/u, /有效(?!期|載荷|負載)/u,
  /相關(?!係數|性分析)/u, /確保/u, /強化(?!學習)/u, /(?<!負載)平衡(?!器)/u,
  /增強|改善|改進|提高|促進|助力|擁抱|把握|做好|做大|做強(?!化)/u,
  /構建|建構(?!子)/u, /可能面臨|需要注意|有一定風險|需要權衡|建議評估|視情況而定|或許/u,
  /潛在(?!客戶)/u, /挑戰(?![-–者])/u,
  /取決於|也許|大概|適當|適度|合理(?!化)|一定程度|某種程度|盡量|儘量|酌情|必要時|不排除/u,
  /更(?!新|換|改|正|迭|替)/u,
];
export function hasSlop(text: string): boolean { return SLOP_BLOCK.some((re) => re.test(text)); }
